/** Wide wordmarks need less height than square marks to read as equal weight. */
function opticalScale(aspect) {
  if (aspect >= 3.4) return 0.56;
  if (aspect >= 2.4) return 0.7;
  if (aspect >= 1.6) return 0.84;
  return 1;
}

fs.mkdirSync(OUT_LOGOS, { recursive: true });
fs.mkdirSync(OUT_BRAND, { recursive: true });

const manifest = [];

for (const file of fs.readdirSync(SRC_LOGOS).sort()) {
  if (!/\.(png|jpe?g|webp)$/i.test(file)) continue;
  const slug = file
    .replace(/\.(png|jpe?g|webp)$/i, "")
    .replace(/[_\s]?logo$/i, "")
    .trim();

  const src = path.join(SRC_LOGOS, file);
  // Trim the transparent margin so the optical maths sees the artwork itself.
  const trimmed = await sharp(src).ensureAlpha().trim({ threshold: 6 }).toBuffer();
  const m = await sharp(trimmed).metadata();
  const aspect = m.width / m.height;
  const targetH = Math.round(CANVAS_H * opticalScale(aspect));

  const scaled = await sharp(trimmed)
    .resize({ height: targetH, width: MAX_W, fit: "inside", withoutEnlargement: false })
    .toBuffer();
  const sm = await sharp(scaled).metadata();

  const top = Math.round((CANVAS_H - sm.height) / 2);
  const out = await sharp(scaled)
    .extend({
      top,
      bottom: CANVAS_H - sm.height - top,
      left: 0,
      right: 0,
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .webp({ quality: 92, alphaQuality: 100 })
    .toBuffer();

  fs.writeFileSync(path.join(OUT_LOGOS, `${slug}.webp`), out);
  const fm = await sharp(out).metadata();
  manifest.push({ slug, name: NAMES[slug] ?? slug, w: fm.width, h: fm.height });
  process.stdout.write(".");
}

/* ── YandNow wordmark ───────────────────────────────────── */
const brand = await sharp("public/logo.png").ensureAlpha().trim({ threshold: 6 }).toBuffer();
const bm = await sharp(brand).metadata();
await sharp(brand).webp({ quality: 95, alphaQuality: 100 }).toFile(path.join(OUT_BRAND, "yandnow.webp"));

// White silhouette: keep the source alpha, replace every colour with white.
const alpha = await sharp(brand).extractChannel("alpha").toBuffer();
await sharp({
  create: { width: bm.width, height: bm.height, channels: 3, background: "#ffffff" },
})
  .joinChannel(alpha)
  .webp({ quality: 95, alphaQuality: 100 })
  .toFile(path.join(OUT_BRAND, "yandnow-white.webp"));

manifest.sort((a, b) => a.name.localeCompare(b.name));

fs.writeFileSync(
  "src/lib/brand.ts",
  `// AUTO-GENERATED by scripts/build-brand.mjs — do not edit by hand.
export type ClientLogo = { slug: string; name: string; w: number; h: number };

/** Client and partner logos, normalised to a common optical height. */
export const clientLogos: ClientLogo[] = ${JSON.stringify(manifest, null, 2)};

/** Every logo asset shares this intrinsic height; width varies. */
export const LOGO_H = ${CANVAS_H};

export const wordmark = {
  colour: { src: "/brand/yandnow.webp", w: ${bm.width}, h: ${bm.height} },
  white: { src: "/brand/yandnow-white.webp", w: ${bm.width}, h: ${bm.height} },
};
`,
);

