/**
 * Normalises brand artwork for the site.
 *
 *   node scripts/build-brand.mjs
 *
 * Client logos arrive at wildly different sizes (150×40 to 5148×1368) with
 * inconsistent transparent padding. Rendering those at one CSS height makes
 * square marks look tiny next to wide wordmarks, so each logo is trimmed, then
 * scaled by an *optical* factor derived from its aspect ratio and padded onto a
 * canvas of identical height. The page can then render every logo at the same
 * height and have them read as the same visual weight.
 *
 * Also emits a white silhouette of the YandNow wordmark for dark backgrounds,
 * built from the source file's own alpha channel so the shape stays exact.
 */
import sharp from "sharp";
import fs from "fs";
import path from "path";

const SRC_LOGOS = "public/y&now client logos";
const OUT_LOGOS = "public/logos";
const OUT_BRAND = "public/brand";
const CANVAS_H = 128; // asset height; the page scales this down uniformly
const MAX_W = 460;

